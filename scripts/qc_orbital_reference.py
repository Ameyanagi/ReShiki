def grid_points(mol):
    """Sample a reproducible off-nucleus grid around the molecular bounding box."""
    atoms = mol.atom_coords()
    lower = atoms.min(axis=0) - 2.5
    upper = atoms.max(axis=0) + 2.5
    rng = np.random.default_rng(20261125)
    points = []
    while len(points) < 32:
        point = rng.uniform(lower, upper)
        if np.linalg.norm(atoms - point, axis=1).min() >= 0.3:
            points.append(point)
    return np.asarray(points)


def write_reference(source, points, energies, values, route):
    """Write source-ordered values after a stable sort of the printed energies."""
    # ORCA supplies the original energy tokens, including their printed precision.
    energy_fields = [energy if isinstance(energy, str) else f"{energy:.17g}" for energy in energies]
    energies = np.asarray(energies, dtype=float)
    assert values.shape == (len(points), len(energies))
    path = QC / "reference" / (Path(source).stem + ".txt")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as output:
        output.write("# Generated by scripts/qc_orbital_reference.py\n")
        output.write(f"# PySCF {pyscf.__version__}; signed in-memory MO values; bohr\n")
        output.write(f"# Route: {route}\n")
        output.write(f"source {source}\npoints {len(points)}\n")
        for point in points:
            output.write(" ".join(f"{coordinate:.17g}" for coordinate in point) + "\n")
        for index, source_index in enumerate(np.argsort(energies, kind="stable")):
            fields = [energy_fields[source_index], *(f"{x:.17g}" for x in values[:, source_index])]
            output.write(f"orbital a {index} " + " ".join(fields) + "\n")


def molden_energies(path):
    return np.array(
        [float(line.split("=", 1)[1]) for line in path.read_text().splitlines() if "Ene=" in line]
    )


def select_molden_mos(mol, mf, limit):
    """Keep occupied MOs, low virtuals, and virtuals rich in the top two l values."""
    occupied = np.flatnonzero(mf.mo_occ > 0)
    if len(mf.mo_energy) <= limit:
        return np.argsort(mf.mo_energy, kind="stable")
    virtuals = np.flatnonzero(mf.mo_occ == 0)
    virtuals = virtuals[np.argsort(mf.mo_energy[virtuals], kind="stable")]
    selected = set(occupied) | set(virtuals[:2])
    ao_l = np.repeat([mol.bas_angular(s) for s in range(mol.nbas)], np.diff(mol.ao_loc_nr()))
    high_l = int(ao_l.max())
    remaining = min(limit, len(mf.mo_energy)) - len(selected)
    for angular, count in ((high_l, (remaining + 1) // 2), (high_l - 1, remaining // 2)):
        weights = np.sum(mf.mo_coeff[ao_l == angular] ** 2, axis=0)
        ranked = virtuals[np.argsort(-weights[virtuals], kind="stable")]
        choices = [index for index in ranked if index not in selected]
        selected.update(choices[:count])
    indices = np.array(sorted(selected))
    return indices[np.argsort(mf.mo_energy[indices], kind="stable")]


def sign_independent_error(values, reference):
    """Allow only one global sign per MO, never component-dependent signs."""
    same = np.max(np.abs(values - reference), axis=0)
    flipped = np.max(np.abs(values + reference), axis=0)
    return float(np.minimum(same, flipped).max())


def validate_molden(path, points, reference):
    mol, _, coefficients, _, _, _ = molden.load(str(path), verbose=0)
    evaluator = "GTOval_cart" if mol.cart else "GTOval_sph"
    values = mol.eval_gto(evaluator, points) @ coefficients
    error = sign_independent_error(values, reference)
    assert error < 1e-9, (path.name, error)
    print(f"  reload max |delta| up to one sign/MO = {error:.9e}", flush=True)


def read_molden_blocks(path):
    """Read the written shell list and MO blocks without interpreting AO conventions."""
    header, mo_text = path.read_text().split("[MO]\n", 1)
    shell_l = []
    for line in header.split("[GTO]\n", 1)[1].splitlines():
        fields = line.split()
        if fields and fields[0] in ("s", "p", "d", "f", "g"):
            shell_l.append("spdfg".index(fields[0]))
    metadata = []
    coefficients = []
    for block in re.split(r"(?=^ Sym=)", mo_text, flags=re.MULTILINE):
        if not block.strip():
            continue
        lines = block.splitlines()
        metadata.append([line for line in lines if "=" in line])
        entries = [line.split() for line in lines if line.split() and line.split()[0].isdigit()]
        assert [int(entry[0]) for entry in entries] == list(range(1, len(entries) + 1))
        coefficients.append([float(entry[1]) for entry in entries])
    return header, shell_l, metadata, np.array(coefficients)


def splice_molden(pure_path, cart_path, output_path, pure_l, flags):
    """Splice already-written shell blocks, including the writer's Cartesian normalization."""
    header, shells, metadata, pure_coefficients = read_molden_blocks(pure_path)
    _, cart_shells, cart_metadata, cart_coefficients = read_molden_blocks(cart_path)
    assert shells == cart_shells
    assert metadata == cart_metadata
    blocks = []
    pure_offset = cart_offset = 0
    for angular in shells:
        pure_count = 2 * angular + 1
        cart_count = (angular + 1) * (angular + 2) // 2
        if angular in pure_l:
            blocks.append(pure_coefficients[:, pure_offset : pure_offset + pure_count])
        else:
            blocks.append(cart_coefficients[:, cart_offset : cart_offset + cart_count])
        pure_offset += pure_count
        cart_offset += cart_count
    assert pure_offset == pure_coefficients.shape[1]
    assert cart_offset == cart_coefficients.shape[1]
    coefficients = np.concatenate(blocks, axis=1)
    header = re.sub(r"^\[(?:5d7f|9g)\]\n", "", header, flags=re.MULTILINE | re.IGNORECASE)
    with output_path.open("w") as output:
        output.write(header.rstrip() + "\n" + "\n".join(flags) + "\n\n[MO]\n")
        for lines, mo in zip(metadata, coefficients, strict=True):
            output.write("\n".join(lines) + "\n")
            for index, coefficient in enumerate(mo, 1):
                output.write(f" {index:3d}    {coefficient:18.14g}\n")
    return shells, coefficients


def mixed_molden_cases(mol, coefficients, energies, occupations, points, reference, pure_path):
    """Use the pure wavefunction in both shell representations, then mix written blocks."""
    mol_cart = mol.copy()
    mol_cart.cart = True
    mol_cart.build(False, False)
    cart_coefficients = mol.cart2sph_coeff() @ coefficients
    sph_ao = mol.eval_gto("GTOval_sph", points)
    cart_ao = mol_cart.eval_gto("GTOval_cart", points)
    transform_error = float(np.max(np.abs(cart_ao @ cart_coefficients - reference)))
    assert transform_error < 1e-12, transform_error
    print(f"  AO_sph = AO_cart @ T: max |delta| = {transform_error:.9e}", flush=True)
    # In the file each Cartesian component has unit norm. Reconstruct shell-wise
    # using PySCF's order and normalization to validate the actual spliced blocks.
    sph_order = molden.order_ao_index(mol)
    cart_order = molden.order_ao_index(mol_cart)
    ordered_sph = sph_ao[:, sph_order]
    cart_norm = np.sqrt(mol_cart.intor("int1e_ovlp").diagonal())
    ordered_cart = (cart_ao / cart_norm)[:, cart_order]
    with tempfile.TemporaryDirectory(prefix="qc-molden-") as temporary:
        cart_path = Path(temporary) / "h2o_cart.molden"
        molden.from_mo(mol_cart, str(cart_path), cart_coefficients, ene=energies, occ=occupations)
        for suffix, pure_l, flags in (
            ("a", {0, 1, 2, 4}, ["[5D10F]", "[9G]"]),
            ("b", {0, 1, 3}, ["[7F]"]),
        ):
            path = QC / "pyscf" / f"h2o_ccpvqz_mixed_{suffix}.molden"
            shells, mixed_coefficients = splice_molden(pure_path, cart_path, path, pure_l, flags)
            pure_offset = cart_offset = 0
            mixed_ao = []
            for angular in shells:
                pure_count = 2 * angular + 1
                cart_count = (angular + 1) * (angular + 2) // 2
                if angular in pure_l:
                    mixed_ao.append(ordered_sph[:, pure_offset : pure_offset + pure_count])
                else:
                    mixed_ao.append(ordered_cart[:, cart_offset : cart_offset + cart_count])
                pure_offset += pure_count
                cart_offset += cart_count
            values = np.concatenate(mixed_ao, axis=1) @ mixed_coefficients.T
            error = float(np.max(np.abs(values - reference)))
            assert error < 1e-9, (path.name, error)
            assert path.stat().st_size < 120 * 1024
            print(
                f"A {path.relative_to(QC)}: {len(energies)} MOs, "
                f"{mixed_coefficients.shape[1]} AOs, flags {' '.join(flags)}; "
                f"shell reconstruction max |delta| = {error:.9e}",
                flush=True,
            )
            write_reference(
                path.relative_to(QC).as_posix(),
                points,
                molden_energies(path),
                reference,
                f"PySCF RHF/cc-pVQZ pure -> Cartesian transform -> shell splice {suffix}",
            )


def run_molden():
    if lib.num_threads() > 1:
        lib.num_threads(1)
    (QC / "pyscf").mkdir(parents=True, exist_ok=True)
    water = "O 0.12 -0.23 0.17; H 0.86 0.34 0.59; H -0.57 0.48 -0.16"
    cases = (
        (
            "ch2o_ccpvtz_pure",
            "C 0 0 0; O 0.05 -0.03 1.21; H 0.94 0.08 -0.55; H -0.90 0.21 -0.62",
            "cc-pVTZ",
            False,
        ),
        ("h2o_ccpvqz_pure", water, "cc-pVQZ", False),
        ("h2o_ccpvqz_cart", water, "cc-pVQZ", True),
        (
            "ch3nh2_631gs_cart",
            "C 0.02 -0.04 0.06; N 1.43 0.09 -0.13; H -0.35 0.94 0.29; "
            "H -0.41 -0.69 0.83; H -0.48 -0.37 -0.86; "
            "H 1.79 0.98 0.24; H 1.88 -0.61 0.42",
            "6-31G*",
            True,
        ),
        (
            "tih2f2_def2tzvp_pure",
            "Ti 0.03 -0.04 0.02; H 1.51 0.38 0.71; H -0.62 1.56 -0.43; "
            "F -0.97 -1.18 0.86; F 0.61 -0.39 -1.64",
            "def2-TZVP",
            False,
        ),
    )
    print(f"Part A: PySCF {pyscf.__version__}; RHF conv_tol=1e-11; one thread", flush=True)
    for stem, atom, basis, cart in cases:
        mol = gto.M(atom=atom, basis=basis, cart=cart, symmetry=False, verbose=0)
        mf = scf.RHF(mol)
        mf.conv_tol = 1e-11
        mf.max_cycle = 150
        mf.chkfile = None
        mf.kernel()
        if not mf.converged:
            print(f"  {stem}: retrying with the Newton RHF solver", flush=True)
            density = mf.make_rdm1()
            mf = mf.newton()
            mf.kernel(dm0=density)
        assert mf.converged, stem
        limit = {"ch3nh2_631gs_cart": 40, "tih2f2_def2tzvp_pure": 25}.get(stem, 20)
        selected = select_molden_mos(mol, mf, limit)
        coefficients = mf.mo_coeff[:, selected]
        energies = mf.mo_energy[selected]
        occupations = mf.mo_occ[selected]
        points = grid_points(mol)
        evaluator = "GTOval_cart" if cart else "GTOval_sph"
        values = mol.eval_gto(evaluator, points) @ coefficients
        path = QC / "pyscf" / (stem + ".molden")
        molden.from_mo(mol, str(path), coefficients, ene=energies, occ=occupations)
        assert path.stat().st_size < 120 * 1024, path.name
        print(
            f"A {path.relative_to(QC)}: RHF E={mf.e_tot:.14f} Ha, "
            f"{mol.nao_nr()} AOs, {len(selected)} MOs; source MO indices {selected.tolist()}",
            flush=True,
        )
        if len(selected) > 20 and stem == "tih2f2_def2tzvp_pure":
            print(
                "  25-MO exception: TiH2F2 has 21 occupied MOs; retained all occupied, "
                "two lowest virtuals, and highest-f/highest-d virtuals",
                flush=True,
            )
        write_reference(
            path.relative_to(QC).as_posix(),
            points,
            molden_energies(path),
            values,
            f"PySCF RHF/{basis}, {'Cartesian' if cart else 'pure'} AO evaluation @ C",
        )
        validate_molden(path, points, values)
        if stem == "h2o_ccpvqz_pure":
            mixed_molden_cases(mol, coefficients, energies, occupations, points, values, path)


FCHK_FIELDS = {
    "Number of atoms",
    "Atomic numbers",
    "Current cartesian coordinates",
    "Charge",
    "Number of electrons",
    "Number of alpha electrons",
    "Number of basis functions",
    "Shell types",
    "Number of primitives per shell",
    "Shell to atom map",
    "Primitive exponents",
    "Contraction coefficients",
    "P(S=P) Contraction coefficients",
    "Alpha Orbital Energies",
    "Alpha MO coefficients",
    "SCF Energy",
}


def read_fchk(path):
    """Read only the numeric records used by the proofs, with Gaussian's declared lengths."""
    records = {}
    lines = iter(path.read_text().splitlines())
    for line in lines:
        name = line[:40].rstrip()
        if name not in FCHK_FIELDS:
            continue
        kind, field = line[40:].split(maxsplit=1)
        dtype = {"I": int, "R": float}[kind]
        if field.startswith("N="):
            size = int(field[2:])
            words = []
            while len(words) < size:
                words.extend(next(lines).split())
            assert len(words) == size, name
            records[name] = np.array(words, dtype=dtype)
        else:
            records[name] = dtype(field)
    return records


def fchk_molecule(records):
    atoms = records["Atomic numbers"]
    coords = records["Current cartesian coordinates"].reshape(records["Number of atoms"], 3)
    labels = [f"{elements.ELEMENTS[z]}{i}" for i, z in enumerate(atoms, 1)]
    basis = {label: [] for label in labels}
    exponents = records["Primitive exponents"]
    contraction = records["Contraction coefficients"]
    offset = 0
    for kind, nprim, atom in zip(
        records["Shell types"],
        records["Number of primitives per shell"],
        records["Shell to atom map"],
        strict=True,
    ):
        if kind >= 2:
            raise ValueError(f"Gaussian Cartesian shell type {kind} is outside this proof")
        section = slice(offset, offset + nprim)
        shells = basis[labels[atom - 1]]
        terms = np.column_stack((exponents[section], contraction[section])).tolist()
        shells.append([0 if kind == -1 else abs(int(kind)), *terms])
        if kind == -1:
            p_coeff = records["P(S=P) Contraction coefficients"][section]
            shells.append([1, *np.column_stack((exponents[section], p_coeff)).tolist()])
        offset += nprim
    assert offset == len(exponents) == len(contraction)
    mol = gto.Mole()
    # Preserve Gaussian's S,P,S,P order after splitting O's two SP shells.
    mol.format_basis = partial(gto.format_basis, sort_basis=False)
    mol.build(
        atom=list(zip(labels, coords, strict=True)),
        basis=basis,
        unit="Bohr",
        charge=int(records["Charge"]),
        spin=int(records["Number of electrons"] % 2),
        verbose=0,
    )
    assert mol.nao == records["Number of basis functions"]
    return mol


def gaussian_m(angular):
    return [0, *(m for n in range(1, angular + 1) for m in (n, -n))]


def gaussian_ao_order(mol):
    """PySCF AO index of each successive Gaussian AO under hypothesis H."""
    order = np.arange(mol.nao)
    for shell, start in enumerate(mol.ao_loc_nr()[:-1]):
        angular = mol.bas_angular(shell)
        if angular >= 2:
            order[start : start + 2 * angular + 1] = start + angular + np.array(gaussian_m(angular))
    return order


def printed_matrix(lines, name, nao):
    """Gaussian prints the lower triangle as successive panels of up to five columns."""
    cursor = lines.index(f"*** {name} ***") + 1
    matrix = np.empty((nao, nao))
    for start in range(0, nao, 5):
        end = min(start + 5, nao)
        assert list(map(int, lines[cursor].split())) == list(range(start + 1, end + 1))
        cursor += 1
        for row in range(start, nao):
            index, *words = lines[cursor].replace("D", "E").split()
            stop = min(row + 1, end)
            assert int(index) == row + 1 and len(words) == stop - start
            matrix[row, start:stop] = matrix[start:stop, row] = words
            cursor += 1
    return matrix


def check_integrals(case, mol, lines, order):
    overlap = mol.intor("int1e_ovlp")
    printed = printed_matrix(lines, "Overlap", mol.nao)
    h_matrix = overlap[np.ix_(order, order)]
    residual = np.max(np.abs(h_matrix - printed))
    diagonal = np.max(np.abs(h_matrix.diagonal() - 1))
    print(f"{case} overlap H max|diff|={residual:.9e}  max|diag-1|={diagonal:.3e}")

    # For each of the five printed slots choose one PySCF m, then its phase.
    starts = [s for i, s in enumerate(mol.ao_loc_nr()[:-1]) if mol.bas_angular(i) == 2]
    d_slots = np.array(starts)[:, None] + np.arange(5)
    best = np.inf
    for perm in permutations(range(-2, 3)):
        alt = order.copy()
        alt[d_slots] = np.array(starts)[:, None] + 2 + np.array(perm)
        permuted = overlap[np.ix_(alt, alt)]
        for phase in product((1, -1), repeat=5):
            if perm == tuple(gaussian_m(2)) and phase == (1,) * 5:
                continue
            signs = np.ones(mol.nao)
            signs[d_slots] = phase
            error = np.max(np.abs(permuted * signs[:, None] * signs - printed))
            if error < best:
                best, best_perm, best_phase = error, perm, phase
    print(
        f"  best of 3839 non-H d conventions: max|diff|={best:.9e}"
        f"  printed slots -> m={best_perm}, phases={best_phase}"
    )
    assert residual < best, f"{case}: a non-H convention fits at least as well as H"
    assert residual < 2e-6 and best > 1e-3 and diagonal < 1e-12

    kinetic = mol.intor("int1e_kin")[np.ix_(order, order)]
    printed = printed_matrix(lines, "Kinetic Energy", mol.nao)
    print(f"  kinetic H max|diff|={np.max(np.abs(kinetic - printed)):.9e} hartree")
    # The printed integrals have six significant digits (including the large O 1s kinetic).
    # Small symmetry-forbidden elements also reflect the fchk's slightly displaced centers.
    rounding = np.zeros_like(printed)
    nonzero = printed != 0
    rounding[nonzero] = 0.5 * 10 ** (np.floor(np.log10(np.abs(printed[nonzero]))) - 5)
    excess = np.max(np.abs(kinetic - printed) - rounding)
    print(f"  kinetic max excess beyond log rounding={excess:.9e} hartree")
    assert excess < 2e-6


def check_log_mos(case, mol, lines, coeff, energies):
    cursor = lines.index("Molecular Orbital Coefficients:") + 1
    labels = []
    for shell in range(mol.nbas):
        angular = mol.bas_angular(shell)
        if angular < 2:
            labels.extend(["S"] if angular == 0 else ["PX", "PY", "PZ"])
        else:
            labels.extend(
                "SPDFG"[angular] + (f"{m:+d}" if m else " 0") for m in gaussian_m(angular)
            )
    printed = np.empty_like(coeff)
    count = 0
    while re.fullmatch(r"[\d ]+", lines[cursor]):
        columns = np.array(lines[cursor].split(), dtype=int) - 1
        assert np.array_equal(columns, np.arange(count, count + len(columns)))
        assert lines[cursor + 2].startswith("Eigenvalues --")
        cursor += 3
        for row, expected in enumerate(labels):
            # Group from the right: the AO label itself can contain a space (e.g. "5D 0").
            fields = lines[cursor].rsplit(maxsplit=len(columns))
            prefix, words = fields[0], fields[1:]
            assert int(prefix.split()[0]) == row + 1
            if count == 0:
                match = re.search(r"\d+([SPDFG][XYZ 0-9+-]*)$", prefix)
                assert match and match[1] == expected, (case, prefix, expected)
            printed[row, columns] = words
            cursor += 1
        count += len(columns)
    assert count == coeff.shape[1], (case, count, coeff.shape)
    diff = np.abs(coeff - printed)
    row, col = np.unravel_index(diff.argmax(), diff.shape)
    print(
        f"{case} AO labels verified, {mol.nao} x {count} coefficients:"
        f" same-order max|log-fchk|={diff[row, col]:.9e} (AO {row + 1}, MO {col + 1})"
    )
    # G09 carbon reverses some exactly equal-energy MO pairs. Try only a full
    # exchange of those two columns: preserve every AO row, sign and coefficient.
    swaps = []
    for group in np.split(np.arange(count), np.flatnonzero(np.diff(energies)) + 1):
        if len(group) == 2:
            original = diff[:, group].max()
            exchanged = np.max(np.abs(coeff[:, group] - printed[:, group[::-1]]))
            if exchanged < original:
                printed[:, group] = printed[:, group[::-1]]
                swaps.append(f"{group[0] + 1}/{group[1] + 1}")
    aligned = np.max(np.abs(printed - coeff))
    if swaps:
        print(f"  {len(swaps)} equal-energy MO pairs reversed (1-based): {', '.join(swaps)}")
        print(f"  after MO exchanges alone: max|log-fchk|={aligned:.9e}")
    # G09 Mo differs by 6.962e-6 in one element; require one log unit at 5 decimals.
    assert aligned <= 1e-5


def carbon_fock(case, mol, coeff, records):
    energies = records["Alpha Orbital Energies"]
    nocc = records["Number of alpha electrons"]
    assert nocc == 3
    rhf = scf.RHF(mol)
    rhf.conv_tol = 1e-11
    overlap, core = rhf.get_ovlp(), rhf.get_hcore()

    def evaluate(c):
        occ = c[:, :nocc]
        density = 2 * occ @ occ.T
        potential = rhf.get_veff(dm=density)
        residuals = np.linalg.norm((core + potential) @ c - (overlap @ c) * energies, axis=0)
        return residuals.max(), rhf.energy_tot(dm=density, h1e=core, vhf=potential)

    residual, energy = evaluate(coeff)
    print(f"{case} carbon Fock H max r_i={residual:.9e}")
    print(f"  E_RHF(D)={energy:.12f}  fchk SCF Energy={records['SCF Energy']:.12f} hartree")
    assert residual < 1e-5
    print("  shell    m       flip(m) max r_i    swap(+m,-m) max r_i")
    for angular in (2, 3, 4):
        centers = np.array(
            [
                s + angular
                for i, s in enumerate(mol.ao_loc_nr()[:-1])
                if mol.bas_angular(i) == angular
            ]
        )
        for m in gaussian_m(angular):
            alternative = coeff.copy()
            alternative[centers + m] *= -1
            flip, _ = evaluate(alternative)
            swap_column = ""
            if m > 0:
                alternative = coeff.copy()
                plus, minus = centers + m, centers - m
                alternative[plus], alternative[minus] = coeff[minus], coeff[plus]
                swap, _ = evaluate(alternative)
                swap_column = f"     {swap:.9e}"
            print(f"    {'dfg'[angular - 2]}     {m:+2d}       {flip:.9e}{swap_column}")


