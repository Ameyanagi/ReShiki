def read_orca_molden(path):
    """Read the orca_2mkl atoms, pure shells, and complete printed alpha MO frame."""
    header, shell_l, metadata, columns = read_molden_blocks(path)
    assert "Molden file created by orca_2mkl" in header
    atom_text, gto_text = header.split("[Atoms] AU\n", 1)[1].split("[GTO]\n", 1)
    atoms = []
    for line in atom_text.strip().splitlines():
        symbol, index, charge, *coords = line.split()
        assert int(index) == len(atoms) + 1 and gto.charge(symbol) == int(charge)
        assert len(coords) == 3
        atoms.append((symbol + index, tuple(map(float, coords))))

    basis = {label: [] for label, _ in atoms}
    flags = set(header.splitlines())
    for angular, flag in ((2, "[5D]"), (3, "[7F]")):
        if angular in shell_l:
            assert flag in flags
    primitives = gto_text.split("[", 1)[0]
    lines = iter(line.split() for line in primitives.splitlines() if line.strip())
    shells = None
    for fields in lines:
        if fields[0].isdigit():
            index, zero = map(int, fields)
            assert zero == 0 and 1 <= index <= len(atoms)
            shells = basis[atoms[index - 1][0]]
        else:
            letter, count, scale = fields
            assert shells is not None and float(scale) == 1
            terms = [tuple(map(float, next(lines))) for _ in range(int(count))]
            assert terms and all(len(term) == 2 and term[0] > 0 for term in terms)
            shells.append(["spdf".index(letter), *terms])
    assert [shell[0] for shells in basis.values() for shell in shells] == shell_l
    energies = []
    for block in metadata:
        fields = dict(line.strip().split("=", 1) for line in block)
        assert fields["Spin"].strip() == "Alpha"
        energies.append(fields["Ene"].strip())
    nao = sum(2 * angular + 1 for angular in shell_l)
    assert columns.shape == (nao, nao)
    return atoms, basis, energies, columns.T


def orca_molecule(atoms, basis, radial):
    if radial == "bare":
        # PySCF multiplies input coefficients by the primitive radial norm
        # before normalizing each contraction. Undo the first step for bare inputs.
        basis = {
            label: [
                [angular, *((a, c / gto.gto_norm(angular, a)) for a, c in terms)]
                for angular, *terms in shells
            ]
            for label, shells in basis.items()
        }
    mol = gto.Mole()
    mol.format_basis = partial(gto.format_basis, sort_basis=False)
    mol.build(atom=atoms, basis=basis, unit="Bohr", cart=False, verbose=0, parse_arg=False)
    return mol


def orca_orders(mol, slots):
    """Try the candidate pure order and each within-d or within-f single transposition."""
    order = gaussian_ao_order(mol)  # p=x,y,z; pure m=0,+1,-1,... in file order
    yield "identity", order
    for angular, rows in slots.items():
        if not rows.size:
            continue
        m = gaussian_m(angular)
        for j, k in combinations(range(len(m)), 2):
            swapped = order.copy()
            swapped[rows[:, j]], swapped[rows[:, k]] = order[rows[:, k]], order[rows[:, j]]
            yield f"swap {'spdf'[angular]}({m[j]:+d},{m[k]:+d})", swapped


def orca_phase_masks(nao, slots):
    """Give each file slot the same phase in every shell of that angular momentum."""
    masks = np.ones((2 ** slots.shape[1], nao), dtype=int)
    for row, phases in zip(masks, product((1, -1), repeat=slots.shape[1]), strict=True):
        row[slots] = phases
    return masks


def phase_errors(overlap, implied, masks):
    signed = masks[:, :, None] * overlap * masks[:, None, :]
    return np.max(np.abs(signed - implied), axis=(1, 2))


def prove_orca_convention(atoms, basis, coeff, *, require_reflection_gap=False):
    """Rank AO hypotheses against (C C^T)^-1, independent of any AO evaluator."""
    eye = np.eye(len(coeff))
    inv_c = np.linalg.solve(coeff, eye)
    implied = inv_c.T @ inv_c
    shell_l = np.array([shell[0] for shells in basis.values() for shell in shells])
    ao_l = np.repeat(shell_l, 2 * shell_l + 1)
    slots = {n: np.flatnonzero(ao_l == n).reshape(-1, 2 * n + 1) for n in (2, 3)}
    d_masks = orca_phase_masks(len(coeff), slots[2])
    f_masks = orca_phase_masks(len(coeff), slots[3]) if slots[3].size else None
    non_f = ao_l != 3
    section = np.ix_(non_f, non_f)
    trials = []
    discarded_bound = np.inf
    for radial in ("normalized", "bare"):
        mol = orca_molecule(atoms, basis, radial)
        raw = mol.intor_symmetric("int1e_ovlp_sph")
        assert np.max(np.abs(raw.diagonal() - 1)) < 1e-12
        for swap, order in orca_orders(mol, slots):
            overlap = raw[np.ix_(order, order)]
            masks = d_masks
            errors = phase_errors(overlap[section], implied[section], d_masks[:, non_f])
            if f_masks is not None:
                # Every discarded d mask has at least this error for *any* f mask.
                discarded_bound = min(discarded_bound, np.partition(errors, 1)[1])
                masks = d_masks[np.argmin(errors)] * f_masks
                errors = phase_errors(overlap, implied, masks)
            for i in np.argsort(errors)[:2]:
                trials.append((errors[i], radial, swap, mol, order, masks[i]))

    trials.sort(key=lambda trial: trial[0])
    residual, radial, swap, mol, order, signs = trials[0]
    alternative, _, alt_swap, *_ = trials[1]
    assert discarded_bound >= alternative  # Certifies the global runner-up.
    margin = alternative - residual
    overlap = mol.intor_symmetric("int1e_ovlp_sph")[np.ix_(order, order)]
    signed_overlap = signs[:, None] * overlap * signs
    orthogonality = np.max(np.abs(coeff.T @ signed_overlap @ coeff - eye))
    expected = np.ones(mol.nao)
    expected[slots[3][:, 5:]] = -1  # The last two file slots are f(+3), f(-3).
    assert radial == "bare" and swap == "identity" and np.array_equal(signs, expected)
    assert max(residual, orthogonality) < 1e-9 and margin > 1e-2
    phases = "d unchanged" + (", f(+3) and f(-3) negated" if slots[3].size else "")
    print(f"  winner: {radial}, {swap} order, {phases}")
    print(f"  max|S_hyp - S_impl|={residual:.9e}  max|C^T S_hyp C - I|={orthogonality:.9e}")
    print(
        f"  best alternative with fixed p phases ({alt_swap}): "
        f"max|S_hyp - S_impl|={alternative:.9e}  margin={margin:.9e}"
    )

    # In real harmonics +m carries cos(m phi) and -m carries sin(|m| phi).
    # Reflecting x takes phi to pi-phi; reflecting y takes phi to -phi.
    # The p slots (x,y,z) have m=(+1,-1,0) in this convention.
    m = np.concatenate([[1, -1, 0] if n == 1 else gaussian_m(n) for n in shell_l])
    x_odd = ((m > 0) & (m % 2 == 1)) | ((m < 0) & (m % 2 == 0))
    for axis, odd in (("x", x_odd), ("y", m < 0)):
        reflection = np.where(odd, -1, 1)
        error = np.max(np.abs(reflection[:, None] * signed_overlap * reflection - implied))
        print(f"  reflected {axis}: max|S_hyp - S_impl|={error:.9e}")
        if require_reflection_gap:
            assert error - residual > 1e-2, (axis, error, residual)
    return mol, order, signs


