def number(value):
    return f"{value:.6f}".rstrip("0").rstrip(".") if isinstance(value, float) else str(value)


def coords(*values):
    return " ".join(number(value) for value in values)


def xml_bytes(root):
    ET.indent(root, space="  ")
    return (
        HEADER + ET.tostring(root, encoding="unicode", short_empty_elements=True) + "\n"
    ).encode()


def stationery_bytes(root, binary=None):
    """Add SDK packed document defaults without changing any drawing objects."""
    binary = codec.to_cdx(xml_bytes(root).decode()) if binary is None else binary
    packed_fonts = b""
    for prefix, tag in [("Label", 0x080A), ("Caption", 0x080B)]:
        font = [
            round(float(root.get(prefix + suffix, default)) * scale)
            for suffix, default, scale in [
                ("Font", "3", 1),
                ("Face", "0", 1),
                ("Size", "10", 20),
                ("Color", "3", 1),
            ]
        ]
        packed_fonts += codec.property_bytes(tag, struct.pack("<HHHH", *font))
    # The reference encoder writes a 22-byte header followed by document tag/ID.
    return binary[:28] + packed_fonts + binary[28:]


def assert_binary_content(root, binary, identifier):
    """Independently decode source binaries, including full stationery artwork."""
    decoded = ET.fromstring(codec.from_cdx(binary))
    if collections.Counter(e.tag for e in decoded.iter()) != collections.Counter(
        e.tag for e in root.iter()
    ):
        raise ValueError(f"Binary codec changed object inventory for {identifier}")
    if [e.text or "" for e in decoded.iter("s")] != [e.text or "" for e in root.iter("s")]:
        raise ValueError(f"Binary codec changed caption/label text for {identifier}")
    return decoded


def png_bytes(seed):
    rng = random.Random(seed)
    pixels = bytes(rng.randrange(256) for _ in range(4 * 4 * 4))
    raw = b"".join(b"\0" + pixels[y * 16 : (y + 1) * 16] for y in range(4))

    def chunk(kind, payload):
        return (
            struct.pack(">I", len(payload))
            + kind
            + payload
            + struct.pack(">I", zlib.crc32(kind + payload))
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", 4, 4, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def bmp_bytes(seed):
    rng = random.Random(seed)
    pixels = bytes(rng.randrange(256) for _ in range(4 * 4 * 3))
    return (
        b"BM"
        + struct.pack("<IHHI", 54 + len(pixels), 0, 0, 54)
        + struct.pack("<IiiHHIIiiII", 40, 4, 4, 1, 24, 0, len(pixels), 2835, 2835, 0, 0)
        + pixels
    )


class Drawing:
    def __init__(self, rng, title):
        self.rng, self.next_id = rng, 1
        self.counts = dict.fromkeys(
            ["atoms", "bonds", "annotations", "arrows", "graphics", "groups", "repeats"], 0
        )
        self.root = ET.Element(
            "CDXML",
            {
                "CreationProgram": "ReShiki synthetic import corpus generator",
                "Name": title,
                "BoundingBox": "0 0 612 792",
                "BondLength": "24",
                "BondSpacing": "18",
                "LineWidth": "0.6",
                "BoldWidth": "2",
                "MarginWidth": "1.6",
                "HashSpacing": "2.5",
                "ChainAngle": "120",
                "LabelFont": "1001",
                "CaptionFont": "1001",
                "LabelSize": "10",
                "CaptionSize": "10",
                "LabelFace": "0",
                "CaptionFace": "0",
                "LabelColor": "3",
                "CaptionColor": "3",
                "color": "3",
                "bgcolor": "2",
            },
        )
        table = ET.SubElement(self.root, "colortable")
        for rgb in [
            (1, 1, 1),
            (0, 0, 0),
            (0.12, 0.35, 0.65),
            (0.80, 0.24, 0.18),
            (0.70, 0.88, 0.79),
        ]:
            ET.SubElement(table, "color", dict(zip("rgb", map(number, rgb))))
        fonts = ET.SubElement(self.root, "fonttable")
        for identifier, family in [(1001, "Arial"), (1002, "Times New Roman"), (1003, "Helvetica")]:
            ET.SubElement(fonts, "font", id=str(identifier), name=family, charset="utf-8")
        self.page = self.add(
            self.root, "page", BoundingBox="0 0 612 792", WidthPages="1", HeightPages="1"
        )

    def add(self, parent, tag, **attrs):
        element = ET.SubElement(
            parent,
            tag,
            id=str(self.next_id),
            **{key: number(value) for key, value in attrs.items()},
        )
        self.next_id += 1
        return element

    def caption(self, parent, x, y, text, runs=None, **attrs):
        caption = self.add(
            parent,
            "t",
            p=coords(x, y),
            BoundingBox=coords(x, y - 12, x + max(24, len(text) * 5), y + 2),
            **attrs,
        )
        for value, face, size, color, font in runs or [(text, 0, 10, 3, 1001)]:
            ET.SubElement(
                caption, "s", font=str(font), size=str(size), color=str(color), face=str(face)
            ).text = value
        self.counts["annotations"] += 1
        return caption

    def molecule(
        self,
        parent,
        x=70,
        y=110,
        count=6,
        ring=False,
        angle=0,
        spacing=24,
        hetero=True,
        aromatic=False,
        display="Solid",
    ):
        fragment = self.add(parent, "fragment")
        points = []
        for i in range(count):
            a = math.radians(angle)
            u, v = (
                (spacing * math.cos(i * math.tau / count), spacing * math.sin(i * math.tau / count))
                if ring
                else (i * spacing * math.sqrt(3) / 2, (i % 2) * spacing / 2)
            )
            points.append(
                (x + u * math.cos(a) - v * math.sin(a), y + u * math.sin(a) + v * math.cos(a))
            )
        atoms = []
        for i, (px, py) in enumerate(points):
            element = (
                8
                if hetero and i == count - 1 and not ring
                else 7
                if hetero and ring and i == 0
                else 6
            )
            attrs = {"NumHydrogens": "0" if aromatic else "1"} if element in (7, 8) else {}
            node = self.add(fragment, "n", p=coords(px, py), Element=str(element), **attrs)
            atoms.append(node)
            if element != 6:
                label = self.add(node, "t", p=coords(px - 3.5, py + 3.5), LabelJustification="Left")
                ET.SubElement(label, "s", font="1001", size="10", color="3", face="96").text = (
                    "O" if element == 8 else "N"
                )
        bonds = []
        for i in range(count if ring else count - 1):
            order = "2" if aromatic and i % 2 == 0 else "1"
            attrs = {"B": atoms[i].get("id"), "E": atoms[(i + 1) % count].get("id"), "Order": order}
            if i == 0 and display != "Solid":
                attrs["Display"] = display
            bonds.append(self.add(fragment, "b", **attrs))
        self.counts["atoms"] += count
        self.counts["bonds"] += len(bonds)
        return fragment, atoms, bonds

    def arrow(self, parent, x=190, y=110, width=60, tail="None", head="Full", **attrs):
        arrow = self.add(
            parent,
            "arrow",
            BoundingBox=coords(x, y - 3, x + width, y + 3),
            Tail3D=coords(x, y, 0),
            Head3D=coords(x + width, y, 0),
            ArrowheadHead=head,
            ArrowheadTail=tail,
            ArrowheadType="Solid",
            FillType="None",
            **attrs,
        )
        self.counts["arrows"] += 1
        return arrow

    def graphic(self, parent, kind="Rectangle", box=(40, 65, 165, 145), **attrs):
        graphic = self.add(parent, "graphic", GraphicType=kind, BoundingBox=coords(*box), **attrs)
        self.counts["graphics"] += 1
        return graphic

    def curve(self, parent, points, **attrs):
        curve = self.add(parent, "curve", CurvePoints=coords(*points), **attrs)
        self.counts["graphics"] += 1
        return curve

    def stamp(self, parent, x, y, size, angle, kind, nested=False):
        """Place an editable stamp with the affine transform baked into points."""
        group = self.add(parent, "group", Integral="yes")
        self.counts["groups"] += 1
        radians = math.radians(angle)
        cosine, sine = math.cos(radians), math.sin(radians)

        def point(u, v):
            return x + size * (u * cosine - v * sine), y + size * (u * sine + v * cosine)

        color = str(self.rng.choice([3, 4, 5]))
        if kind in ("star", "hexagon", "warning"):
            vertices = 10 if kind == "star" else 6 if kind == "hexagon" else 3
            points = []
            for index in range(vertices):
                radius = 0.45 if kind == "star" and index % 2 else 1
                a = index * math.tau / vertices - math.pi / 2
                xy = point(radius * math.cos(a), radius * math.sin(a))
                points.extend(xy * 3)
            self.curve(group, points, CurveType="1", Closed="yes", color=color)
        else:
            major, minor = point(1, 0), point(0, 0.8)
            self.graphic(
                group,
                "Oval",
                (x - size, y - size, x + size, y + size),
                Center3D=coords(x, y, 0),
                MajorAxisEnd3D=coords(*major, 0),
                MinorAxisEnd3D=coords(*minor, 0),
                color=color,
            )
        if nested:
            symbol = self.add(group, "group")
            self.counts["groups"] += 1
            for a, b in [((-0.4, -0.4), (0.4, 0.4)), ((-0.4, 0.4), (0.4, -0.4))]:
                self.graphic(symbol, "Line", (*point(*a), *point(*b)), color=color)
        elif kind == "warning":
            self.caption(group, x - 1, y + size * 0.3, "!", runs=[("!", 1, 10, int(color), 1001)])
        else:
            points = []
            for u, v in [(-0.45, 0), (-0.1, 0.4), (0.5, -0.4)]:
                points.extend(point(u, v) * 3)
            self.curve(group, points, color=color)
        return group


