def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument(
        "--extra-cases",
        type=int,
        default=DEFAULT_EXTRA_CASES,
        help="Append fresh feature combinations after the retained 104 cases",
    )
    parser.add_argument("--output", type=Path, default=DESTINATION)
    parser.add_argument(
        "--check", action="store_true", help="Compare all generated bytes; do not write"
    )
    args = parser.parse_args()
    if args.extra_cases < 0:
        parser.error("--extra-cases must be nonnegative")
    outputs = generate(args.seed, args.extra_cases)
    actual = (
        {str(path.relative_to(args.output)) for path in args.output.rglob("*") if path.is_file()}
        if args.output.exists()
        else set()
    )
    mismatches = [
        name
        for name, data in outputs.items()
        if not (args.output / name).is_file() or (args.output / name).read_bytes() != data
    ]
    unexpected = sorted(actual - outputs.keys())
    if args.check:
        if mismatches or unexpected:
            print(
                json.dumps(
                    {"different_or_missing": mismatches, "unexpected": unexpected}, indent=2
                ),
                file=sys.stderr,
            )
            return 1
    else:
        if unexpected:
            parser.error(
                "Output contains files not owned by this generator: " + ", ".join(unexpected)
            )
        previous_manifest = args.output / "manifest.json"
        if actual:
            if not previous_manifest.is_file():
                parser.error(
                    "Refusing to overwrite an existing output without its ownership manifest"
                )
            previous = json.loads(previous_manifest.read_text())
            if (
                previous.get("provenance", {}).get("generator")
                != "scripts/generate_chemdraw_import_corpus.py"
            ):
                parser.error("Output manifest belongs to another generator")
            owned = {"manifest.json", "README.md"} | {
                name for case in previous["cases"] for name in case["files"].values() if name
            }
            if actual - owned:
                parser.error(
                    "Refusing to overwrite files absent from the previous ownership manifest"
                )
        for name, data in outputs.items():
            path = args.output / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    case_count = json.loads(outputs["manifest.json"])["case_count"]
    print(
        f"{'Verified' if args.check else 'Generated'} {case_count} cases, {len(outputs)} files, {sum(map(len, outputs.values())):,} bytes; seed {args.seed}."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
