        classification = case["classification"]
        base = f"{case.get('fixture_partition', classification)}/{identifier}"
        data = xml_bytes(d.root)
        object_ids = [int(el.get("id")) for el in d.root.iter() if el.get("id") is not None]
        if len(set(object_ids)) != len(object_ids):
            raise ValueError(f"Duplicate object/font identifier in generated {identifier}")
        files = {"cdxml": base + ".cdxml", "cdx": None, "cds": None}
        outputs[files["cdxml"]] = data[:-9] if case.get("truncate") else data
        encoder_limitations = []
        try:
            binary = codec.to_cdx(data.decode())
        except (ValueError, UnicodeEncodeError) as error:
            encoder_limitations.append(str(error))
        else:
            assert_binary_content(d.root, binary, identifier)
            stationery = stationery_bytes(d.root, binary)
            assert_binary_content(d.root, stationery, identifier + " stationery")
            if case.get("header_variant") == "28-byte":
                binary = binary[:22] + bytes(6) + binary[22:]
            files["cdx"] = base + ".cdx"
            outputs[files["cdx"]] = binary[:-5] if case.get("truncate") else binary
            files["cds"] = base + ".drawing.cds"
            outputs[files["cds"]] = stationery[:-5] if case.get("truncate") else stationery
        counts = dict(d.counts)
        counts.update(case.pop("counts_override", {}))
        expected = {
            "outcome": "accept" if classification == "supported" else "reject",
            "counts": counts if classification == "supported" else {},
            "preservation": case.pop("preservation"),
        }
        if classification == "supported":
            if len(d.root.findall("page")) > 1:
                expected["required_warning_substrings"] = ["page"]
