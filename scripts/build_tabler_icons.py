"""Build the compact Tabler outline icon asset from a pinned npm tarball."""

import argparse
import hashlib
import json
import shutil
import tarfile
from base64 import b64encode
from io import BytesIO
from pathlib import Path
from tempfile import TemporaryFile
from urllib.request import urlopen

from download_tls import verified_context

VERSION = "3.50.0"
URL = f"https://registry.npmjs.org/@tabler/icons/-/icons-{VERSION}.tgz"
INTEGRITY = "sha512-HflLxyrH1cqC7s7jzQGSjpsTAVIoaf7+/yHjbdM59rJQBMjliibp+LYhDPFxOMcwa1M8DNpOk6ENzQiWn9a1Dg=="
OUTPUT = Path(__file__).resolve().parents[1] / "assets/icons/tabler-outline.tsv"
HEADER = (
    f"# Tabler Icons {VERSION} outline icons (MIT, see licenses/tabler-icons). "
    "Generated by scripts/build_tabler_icons.py; do not edit."
)


def build_tsv(tarball: bytes, *, integrity: str = INTEGRITY) -> tuple[bytes, int]:
    actual = "sha512-" + b64encode(hashlib.sha512(tarball).digest()).decode("ascii")
    if actual != integrity:
        raise ValueError(
            f"Tabler Icons tarball SHA-512 integrity mismatch: {actual} != {integrity}"
        )

    with tarfile.open(fileobj=BytesIO(tarball), mode="r:gz") as archive:
        outline_file = archive.extractfile("package/tabler-nodes-outline.json")
        icons_file = archive.extractfile("package/icons.json")
        assert outline_file is not None and icons_file is not None
        outline = json.load(outline_file)
        icons = json.load(icons_file)

    lines = [HEADER]
    for name, nodes in sorted(outline.items()):
        icon = icons[name]
        tags = [str(tag).lower() for tag in icon["tags"]]
        assert all(not any(char in tag for char in "\t,\r\n") for tag in tags), name
        name_words = set(name.split("-"))
        tags_field = ",".join(tag for tag in dict.fromkeys(tags) if tag not in name_words)

        paths = []
        for node, attributes in nodes:
            assert node == "path", name
            d = attributes["d"]
            assert d.startswith(("M", "m")) and "|" not in d and "\t" not in d, name
            paths.append("*" + d if attributes.get("fill") == "currentColor" else d)
        lines.append("\t".join((name, icon.get("category", ""), tags_field, "|".join(paths))))

    return ("\n".join(lines) + "\n").encode("utf-8"), len(outline)


def download_tarball() -> bytes:
    with (
        urlopen(URL, timeout=30, context=verified_context()) as response,
        TemporaryFile() as tarball,
    ):
        shutil.copyfileobj(response, tarball)
        tarball.seek(0)
        return tarball.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tarball", type=Path)
    args = parser.parse_args()

    tarball = args.tarball.read_bytes() if args.tarball else download_tarball()
    try:
        tsv, count = build_tsv(tarball)
    except ValueError as error:
        raise SystemExit(str(error)) from error
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(tsv)
    print(f"{count:,} icons, {len(tsv):,} bytes, SHA-256 {hashlib.sha256(tsv).hexdigest()}")


if __name__ == "__main__":
    main()
