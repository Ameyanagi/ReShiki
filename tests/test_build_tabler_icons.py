"""Check compact Tabler icon generation and the Japanese search index."""

import hashlib
import json
import sys
import tarfile
import unittest
from base64 import b64encode
from io import BytesIO
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from build_tabler_icons import HEADER, build_tsv


class TablerIconTests(unittest.TestCase):
    def test_build_tsv(self):
        buffer = BytesIO()
        with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
            for name, data in {
                "tabler-nodes-outline.json": {
                    "test-tube": [["path", {"d": "m1 2l3 4"}]],
                    "atom": [
                        ["path", {"d": "M1 2 L3 4"}],
                        [
                            "path",
                            {
                                "d": "M5 6z",
                                "fill": "currentColor",
                                "stroke": "none",
                                "opacity": "0.5",
                            },
                        ],
                        ["path", {"d": "M7 8z", "fill": "currentColor"}],
                        ["path", {"d": "M9 10z", "stroke": "none"}],
                        [
                            "path",
                            {"d": "m11 12l1 1", "fill": "none", "stroke": "currentColor"},
                        ],
                    ],
                },
                "icons.json": {
                    "test-tube": {"tags": ["Test", 42, "Glass", "42", "glass", "TUBE", 7]},
                    "atom": {"category": "Science", "tags": ["Physics", "ATOM"]},
                },
            }.items():
                body = json.dumps(data).encode("utf-8")
                member = tarfile.TarInfo(f"package/{name}")
                member.size = len(body)
                archive.addfile(member, BytesIO(body))
        tarball = buffer.getvalue()
        integrity = "sha512-" + b64encode(hashlib.sha512(tarball).digest()).decode("ascii")

        tsv, count = build_tsv(tarball, integrity=integrity)
        self.assertEqual(count, 2)
        self.assertEqual(
            tsv,
            b"# Tabler Icons 3.50.0 outline icons (MIT, see licenses/tabler-icons). "
            b"Generated by scripts/build_tabler_icons.py; do not edit.\n"
            b"atom\tScience\tphysics\tM1 2 L3 4|*!M5 6z|*M7 8z|!M9 10z|m11 12l1 1\n"
            b"test-tube\t\t42,glass,7\tm1 2l3 4\n",
        )

    def test_integrity_mismatch_is_refused_before_opening_archive(self):
        with self.assertRaisesRegex(ValueError, "SHA-512 integrity mismatch"):
            build_tsv(b"invalid tarball")

    def test_repository_assets(self):
        assets = ROOT / "assets/icons"
        header, *outline_rows = (
            (assets / "tabler-outline.tsv").read_text(encoding="utf-8").splitlines()
        )
        self.assertEqual(header, HEADER)
        self.assertEqual(len(outline_rows), 5203)
        names = [row.split("\t", 1)[0] for row in outline_rows]
        self.assertEqual(names, sorted(set(names)))
        paths_by_name = {row.split("\t")[0]: row.split("\t")[3].split("|") for row in outline_rows}
        no_stroke = [
            (name, path)
            for name, paths in paths_by_name.items()
            for path in paths
            if path.startswith(("!", "*!"))
        ]
        self.assertEqual(len(no_stroke), 13)
        self.assertTrue(all(path.startswith("*!") for _, path in no_stroke))
        self.assertIn("*!M12 21a9 9 0 0 0 0 -18m0 0v18", paths_by_name["percentage-50"])
        self.assertEqual(
            sum(
                path.startswith("*") and not path.startswith("*!")
                for paths in paths_by_name.values()
                for path in paths
            ),
            68,
        )

        ja_header, *ja_rows = (assets / "tabler-ja.tsv").read_text(encoding="utf-8").splitlines()
        self.assertEqual(
            ja_header,
            "# Japanese search words for Tabler icons (ReShiki's own list). "
            'name<TAB>words separated by ","',
        )
        ja_names = [row.split("\t", 1)[0] for row in ja_rows]
        self.assertEqual(ja_names, sorted(set(ja_names)))
        self.assertEqual(set(ja_names) - set(names), set())
