use opsin::{
    ambiguity, fragment_tools,
    graph::{AtomId, Graph},
    smiles::build_fragment,
};
fn selected(s: &str) -> Option<Vec<AtomId>> {
    if s == "NULL" {
        None
    } else {
        Some(if s.is_empty() {
            Vec::new()
        } else {
            s.split(',').map(|x| AtomId(x.parse().unwrap())).collect()
        })
    }
}
#[test]
fn source_progressive_substitution_and_ambiguity_decisions() {
    assert_eq!(FROZEN.lines().count(), 2160);
    for (index, line) in FROZEN.lines().enumerate() {
        let p: Vec<_> = line.split('\t').collect();
        let mut graph = Graph::default();
        let fragment = build_fragment(&mut graph, p[0], "", "none").unwrap();
        let required = p[1].parse().unwrap();
        let order = p[2].parse().unwrap();
        let take_out = p[3] == "true";
        let preserve = p[4] == "true";
        let preferred = p[5].parse::<i32>().unwrap();
        let preferred = if preferred < 0 {
            None
        } else {
            Some(AtomId(preferred as usize))
        };
        graph.fragment_mut(fragment).default_in_atom = preferred;
        let result = fragment_tools::find_n_atoms_for_substitution(
            &graph,
            &graph.fragment(fragment).atoms,
            preferred,
            required,
            order,
            take_out,
            preserve,
        )
        .unwrap();
        assert_eq!(result, selected(p[6]), "case {index}: {line}");
        if let Some(atoms) = result.filter(|atoms| !atoms.is_empty()) {
            let before = graph.clone();
            assert_eq!(
                ambiguity::is_substitution_ambiguous(&graph, &atoms, required).unwrap(),
                p[7] == "true",
                "ambiguous case {index}: {line}"
            );
            assert_eq!(
                ambiguity::use_atom_environments_to_give_plausible_substitution(
                    &graph, &atoms, required
                )
                .unwrap(),
                selected(p[8]),
                "plausible case {index}: {line}"
            );
            assert_eq!(
                ambiguity::all_atoms_equivalent(&graph, &atoms).unwrap(),
                p[9] == "true",
                "equivalent case {index}: {line}"
            );
            assert_eq!(graph, before, "transient ambiguity analysis changed graph");
        }
    }
}
